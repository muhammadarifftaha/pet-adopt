// Where uploaded files live: S3-compatible object storage (AWS S3, or any provider or server that
// speaks the S3 API, through S3_ENDPOINT), set by the S3_* variables. There is no local-disk
// option: the server keeps no files of its own, so it can be replaced, scaled or run serverless.
// For development, docker-compose.yml runs an S3-compatible server.
// Visitors never talk to the bucket: the /media route reads from here, so the CSP and next/image
// only ever see this site's own URLs, and the bucket can stay private.
import { SAFE_STORAGE_KEY } from './media-url'

export type StoredFile = { body: Buffer; contentType?: string }

export interface Storage {
  put(key: string, body: Buffer, contentType: string): Promise<void>
  get(key: string): Promise<StoredFile | null>
  /** Whether a file is stored, without downloading it. */
  exists(key: string): Promise<boolean>
  delete(key: string): Promise<void>
  /** Where files go, for logs and scripts. Never includes a secret. */
  describe(): string
}

// Keys are generated by the server. Refuse anything else so a key can never climb out of the folder.
function assertKey(key: string) {
  if (!SAFE_STORAGE_KEY.test(key)) throw new Error(`Unsafe storage key: ${key}`)
}

export type S3Settings = {
  bucket: string
  region: string
  endpoint?: string
  forcePathStyle: boolean
  /** Prepended to every key, so several sites or environments can share one bucket. */
  prefix: string
  accessKeyId?: string
  secretAccessKey?: string
}

/**
 * Reads and checks the S3_* variables. Throws with a message naming the variable to fix, so a
 * misconfigured bucket fails at the first upload or image with a clear reason.
 */
export function s3Settings(env: NodeJS.ProcessEnv = process.env): S3Settings {
  const bucket = env.S3_BUCKET?.trim()
  if (!bucket) {
    throw new Error(
      'Uploads need S3-compatible storage: set S3_BUCKET and the other S3_* variables (see .env.example). ' +
        'For development, `docker compose up -d garage` runs one.',
    )
  }
  const accessKeyId = env.S3_ACCESS_KEY_ID?.trim() || undefined
  const secretAccessKey = env.S3_SECRET_ACCESS_KEY?.trim() || undefined
  if (Boolean(accessKeyId) !== Boolean(secretAccessKey)) {
    throw new Error('Set both S3_ACCESS_KEY_ID and S3_SECRET_ACCESS_KEY, or neither.')
  }
  // The example file's placeholders, left as they were: say so, instead of a refused request later.
  if ([accessKeyId, secretAccessKey].some((key) => key && /^your-/i.test(key))) {
    throw new Error('S3_ACCESS_KEY_ID and S3_SECRET_ACCESS_KEY still hold the placeholders from .env.example. Replace them with your own keys.')
  }
  // Without keys the SDK looks for credentials itself (an IAM role on AWS). Elsewhere that finds
  // nothing, so production insists on them.
  if (env.NODE_ENV === 'production' && !accessKeyId) {
    throw new Error('S3_BUCKET is set, so S3_ACCESS_KEY_ID and S3_SECRET_ACCESS_KEY are required too.')
  }

  const endpoint = env.S3_ENDPOINT?.trim() || undefined
  if (endpoint) {
    let url: URL
    try {
      url = new URL(endpoint)
    } catch {
      throw new Error(`S3_ENDPOINT must be a full URL such as https://s3.example.com, not "${endpoint}".`)
    }
    if (url.protocol !== 'https:' && url.protocol !== 'http:') throw new Error('S3_ENDPOINT must start with https:// (or http:// for a local server).')
    if (url.pathname.replace(/\/+$/, '') !== '') throw new Error('S3_ENDPOINT is the server address only; put the bucket name in S3_BUCKET.')
  }

  const pathStyle = env.S3_FORCE_PATH_STYLE?.trim().toLowerCase()
  if (pathStyle && !['true', 'false', '1', '0'].includes(pathStyle)) throw new Error('S3_FORCE_PATH_STYLE must be true or false.')

  let prefix = env.S3_PREFIX?.trim() ?? ''
  if (prefix) {
    prefix = prefix.replace(/^\/+/, '').replace(/\/*$/, '/')
    if (!/^[A-Za-z0-9][A-Za-z0-9._-]*(\/[A-Za-z0-9][A-Za-z0-9._-]*)*\/$/.test(prefix)) {
      throw new Error('S3_PREFIX may hold letters, digits, ".", "_", "-" and "/" between folder names (for example site/uploads).')
    }
  }

  return {
    bucket,
    // us-east-1 is AWS's default region, and S3-compatible services accept it or ignore the region.
    region: env.S3_REGION?.trim() || 'us-east-1',
    endpoint,
    // Path style (endpoint/bucket/key) works with every S3-compatible server; virtual-hosted style
    // (bucket.endpoint/key) needs DNS for each bucket. AWS itself uses virtual-hosted.
    forcePathStyle: pathStyle ? pathStyle === 'true' || pathStyle === '1' : Boolean(endpoint),
    prefix,
    accessKeyId,
    secretAccessKey,
  }
}

async function s3Storage(settings: S3Settings = s3Settings()): Promise<Storage> {
  const { S3Client, PutObjectCommand, GetObjectCommand, HeadObjectCommand, DeleteObjectCommand } = await import('@aws-sdk/client-s3')
  const { bucket, prefix } = settings
  const client = new S3Client({
    region: settings.region,
    endpoint: settings.endpoint,
    forcePathStyle: settings.forcePathStyle,
    credentials: settings.accessKeyId && settings.secretAccessKey ? { accessKeyId: settings.accessKeyId, secretAccessKey: settings.secretAccessKey } : undefined,
    // Newer SDKs add CRC32 checksums to every request by default, which some S3-compatible services
    // reject or mishandle. Only send and check them where the S3 API requires it, as before.
    requestChecksumCalculation: 'WHEN_REQUIRED',
    responseChecksumValidation: 'WHEN_REQUIRED',
    // A stalled connection must not hang a request forever (the SDK retries a few times by default).
    requestHandler: { requestTimeout: 15_000, connectionTimeout: 5_000 },
    maxAttempts: 3,
  })
  const at = (key: string) => {
    assertKey(key)
    return prefix + key
  }
  const notFound = (error: unknown) => {
    const { name, $metadata } = error as { name?: string; $metadata?: { httpStatusCode?: number } }
    return name === 'NoSuchKey' || name === 'NotFound' || $metadata?.httpStatusCode === 404
  }
  return {
    async put(key, body, contentType) {
      await client.send(new PutObjectCommand({ Bucket: bucket, Key: at(key), Body: body, ContentType: contentType }))
    },
    async get(key) {
      try {
        const result = await client.send(new GetObjectCommand({ Bucket: bucket, Key: at(key) }))
        if (!result.Body) return null
        const bytes = await result.Body.transformToByteArray()
        // A view over the same memory, not a second copy.
        return { body: Buffer.from(bytes.buffer, bytes.byteOffset, bytes.byteLength), contentType: result.ContentType }
      } catch (error) {
        if (notFound(error)) return null
        throw error
      }
    },
    async exists(key) {
      try {
        await client.send(new HeadObjectCommand({ Bucket: bucket, Key: at(key) }))
        return true
      } catch (error) {
        if (notFound(error)) return false
        throw error
      }
    },
    async delete(key) {
      await client.send(new DeleteObjectCommand({ Bucket: bucket, Key: at(key) }))
    },
    describe: () => `bucket "${bucket}"${prefix ? ` under ${prefix}` : ''} at ${settings.endpoint ?? `AWS S3 (${settings.region})`}`,
  }
}

let cached: Promise<Storage> | undefined

export function getStorage(): Promise<Storage> {
  // s3Settings() runs inside, so missing settings reject here (and are tried again next time).
  cached ??= Promise.resolve().then(() => s3Storage())
  cached.catch(() => {
    cached = undefined
  })
  return cached
}

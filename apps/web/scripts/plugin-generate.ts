/**
 * Turns a plugin's schema into the migrations it ships.
 *   pnpm plugin:generate plugins/form-builder add_notes
 *
 * The folder holds `schema/sqlite.ts` and `schema/pg.ts` (twins, relative imports only: drizzle-kit
 * loads them without the app's path aliases). This runs drizzle-kit for both into `drizzle/sqlite`
 * and `drizzle/pg` in that folder, then writes `migrations.ts` with every migration's SQL inlined,
 * which the plugin passes as `storage.migrations`. Inlined, so it works the same from a folder in
 * this repo or from an npm package (whose files may not be on disk where the server runs).
 *
 * Commit the `drizzle/` folder too: drizzle-kit compares against its snapshots for the next change.
 * Never edit or delete a migration that has shipped; change the schema and run this again.
 */
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

const [dirArg, nameArg = 'migration'] = process.argv.slice(2)
if (!dirArg) {
  console.error('Usage: pnpm plugin:generate <plugin folder> [migration name]')
  process.exit(1)
}
if (!/^[a-z0-9_]+$/.test(nameArg)) {
  console.error('The migration name must be lowercase letters, digits and _ (it becomes part of the id).')
  process.exit(1)
}

// pnpm runs this inside apps/web; resolve the folder from where the command was typed (INIT_CWD).
const dir = path.resolve(process.env.INIT_CWD ?? process.cwd(), dirArg)
const dialects = [
  { key: 'sqlite', kit: 'sqlite' },
  { key: 'pg', kit: 'postgresql' },
] as const

for (const { key, kit } of dialects) {
  const schema = path.join(dir, 'schema', `${key}.ts`)
  if (!fs.existsSync(schema)) {
    console.error(`Missing ${path.relative(process.cwd(), schema)}: a plugin's tables live in schema/sqlite.ts and schema/pg.ts.`)
    process.exit(1)
  }
  const result = spawnSync(
    'pnpm',
    ['exec', 'drizzle-kit', 'generate', '--dialect', kit, '--schema', schema, '--out', path.join(dir, 'drizzle', key), '--name', nameArg],
    { stdio: 'inherit' },
  )
  if (result.status !== 0) process.exit(result.status ?? 1)
}

type Journal = { entries: Array<{ idx: number; tag: string }> }
const read = (key: string) => {
  const out = path.join(dir, 'drizzle', key)
  const file = path.join(out, 'meta', '_journal.json')
  const journal: Journal = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : { entries: [] }
  return journal.entries.map((entry) => ({ tag: entry.tag, sql: fs.readFileSync(path.join(out, `${entry.tag}.sql`), 'utf8') }))
}
const sqlite = read('sqlite')
const pg = read('pg')

// The two must move together: one migration per change, in each dialect, with the same name.
if (sqlite.length !== pg.length || sqlite.some((m, i) => m.tag !== pg[i].tag)) {
  console.error(
    'The SQLite and Postgres migrations do not pair up:\n' +
      `  sqlite: ${sqlite.map((m) => m.tag).join(', ') || '(none)'}\n` +
      `  pg:     ${pg.map((m) => m.tag).join(', ') || '(none)'}\n` +
      'Keep schema/sqlite.ts and schema/pg.ts in step, and delete a half-made migration that has not shipped.',
  )
  process.exit(1)
}
if (!sqlite.length) {
  console.error('No migrations yet: the schema files declare no tables.')
  process.exit(1)
}

const body = sqlite
  .map((m, i) => `  {\n    id: ${JSON.stringify(m.tag)},\n    sqlite: ${JSON.stringify(m.sql)},\n    pg: ${JSON.stringify(pg[i].sql)},\n  },`)
  .join('\n')
const output = `// Generated by \`pnpm plugin:generate\` from schema/sqlite.ts and schema/pg.ts. Do not edit:
// change the schema and run it again. A migration that has shipped must never change.
export const migrations: ReadonlyArray<{ id: string; sqlite: string; pg: string }> = [
${body}
]
`
fs.writeFileSync(path.join(dir, 'migrations.ts'), output)
console.log(`Wrote ${path.relative(process.cwd(), path.join(dir, 'migrations.ts'))} (${sqlite.length} migration${sqlite.length === 1 ? '' : 's'}).`)

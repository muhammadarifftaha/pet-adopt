// Where uploaded files live: local disk by default, S3-compatible storage (AWS S3, Cloudflare R2,
// MinIO...) when S3_BUCKET is set. Visitors never talk to the bucket: the /media route reads from
// here, so the CSP and next/image only ever see this site's own URLs.
import { promises as fs } from 'node:fs'
import path from 'node:path'

import { SAFE_FILENAME } from './media-url'

export type StoredFile = { body: Buffer; contentType?: string }

export interface Storage {
  put(key: string, body: Buffer, contentType: string): Promise<void>
  get(key: string): Promise<StoredFile | null>
  delete(key: string): Promise<void>
}

// Keys are generated by the server. Refuse anything else so a key can never climb out of the folder.
function assertKey(key: string) {
  if (!SAFE_FILENAME.test(key)) throw new Error(`Unsafe storage key: ${key}`)
}

function localStorage(dir: string): Storage {
  // The upload folder is chosen at runtime, so keep Turbopack from tracing the whole project for it.
  const root = path.resolve(/* turbopackIgnore: true */ process.cwd(), dir)
  return {
    async put(key, body) {
      assertKey(key)
      await fs.mkdir(root, { recursive: true })
      await fs.writeFile(path.join(root, key), body)
    },
    async get(key) {
      assertKey(key)
      try {
        return { body: await fs.readFile(path.join(root, key)) }
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null
        throw error
      }
    },
    async delete(key) {
      assertKey(key)
      await fs.rm(path.join(root, key), { force: true })
    },
  }
}

async function s3Storage(): Promise<Storage> {
  const bucket = process.env.S3_BUCKET as string
  const accessKeyId = process.env.S3_ACCESS_KEY_ID
  const secretAccessKey = process.env.S3_SECRET_ACCESS_KEY
  if (process.env.NODE_ENV === 'production' && (!accessKeyId || !secretAccessKey)) {
    throw new Error('S3_BUCKET is set, so S3_ACCESS_KEY_ID and S3_SECRET_ACCESS_KEY are required too.')
  }
  const { S3Client, PutObjectCommand, GetObjectCommand, DeleteObjectCommand } = await import('@aws-sdk/client-s3')
  const endpoint = process.env.S3_ENDPOINT || undefined
  const client = new S3Client({
    region: process.env.S3_REGION || 'auto',
    endpoint,
    forcePathStyle: Boolean(endpoint),
    credentials: accessKeyId && secretAccessKey ? { accessKeyId, secretAccessKey } : undefined,
  })
  return {
    async put(key, body, contentType) {
      assertKey(key)
      await client.send(new PutObjectCommand({ Bucket: bucket, Key: key, Body: body, ContentType: contentType }))
    },
    async get(key) {
      assertKey(key)
      try {
        const result = await client.send(new GetObjectCommand({ Bucket: bucket, Key: key }))
        if (!result.Body) return null
        return { body: Buffer.from(await result.Body.transformToByteArray()), contentType: result.ContentType }
      } catch (error) {
        if ((error as { name?: string }).name === 'NoSuchKey') return null
        throw error
      }
    },
    async delete(key) {
      assertKey(key)
      await client.send(new DeleteObjectCommand({ Bucket: bucket, Key: key }))
    },
  }
}

let cached: Promise<Storage> | undefined

export function getStorage(): Promise<Storage> {
  cached ??= process.env.S3_BUCKET ? s3Storage() : Promise.resolve(localStorage(process.env.UPLOAD_DIR || './media'))
  cached.catch(() => {
    cached = undefined
  })
  return cached
}
